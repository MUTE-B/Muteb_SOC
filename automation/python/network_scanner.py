# ----------------------------------------------------------
# استيراد المكتبات
# ----------------------------------------------------------

import os
import socket
import datetime


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT = os.path.abspath(
    os.path.join(
        os.path.dirname(__file__),
        "..",
        ".."
    )
)


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR = os.path.join(
    PROJECT_ROOT,
    "reports"
)

os.makedirs(
    REPORT_DIR,
    exist_ok=True
)


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE = os.path.join(
    REPORT_DIR,
    "network_scan_report.txt"
)


# ----------------------------------------------------------
# عنوان الهدف
# ----------------------------------------------------------

TARGET = "127.0.0.1"


# ----------------------------------------------------------
# قائمة المنافذ الشائعة
# ----------------------------------------------------------

PORTS = [

    20,
    21,
    22,
    23,
    25,
    53,
    80,
    110,
    111,
    135,
    139,
    143,
    389,
    443,
    445,
    587,
    993,
    995,
    1433,
    1521,
    3306,
    3389,
    5432,
    5900,
    8080

]


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

with open(

    REPORT_FILE,

    "w",

    encoding="utf-8"

) as report:


    report.write(
        "============================================================\n"
    )

    report.write(
        "                Network Scan Report\n"
    )

    report.write(
        "============================================================\n\n"
    )

    report.write(
        f"Generated : {datetime.datetime.now()}\n\n"
    )

    report.write(
        f"Target : {TARGET}\n\n"
    )


    for port in PORTS:

        sock = socket.socket(

            socket.AF_INET,

            socket.SOCK_STREAM

        )

        sock.settimeout(1)


        result = sock.connect_ex(

            (

                TARGET,

                port

            )

        )


        if result == 0:

            try:

                service = socket.getservbyport(port)

            except Exception:

                service = "Unknown"


            report.write(

                f"[OPEN] Port {port:<5} Service : {service}\n"

            )


        sock.close()


    report.write(

        "\n============================================================\n"

    )

    report.write(

        "Network Scan Completed Successfully\n"

    )

    report.write(

        "============================================================\n"

    )


# ----------------------------------------------------------
# عرض رسالة النجاح
# ----------------------------------------------------------

print()

print("============================================================")

print("Network scan completed successfully.")

print()

print("Report saved to:")

print()

print(REPORT_FILE)

print()

print("============================================================")
