#!/bin/bash

# ==========================================================
# الملف:
# firewall_status.sh
#
# الهدف:
# إجراء تدقيق شامل لإعدادات جدار الحماية.
#
# يقوم هذا السكربت بعرض:
#
# - حالة UFW
# - قواعد UFW
# - حالة خدمة UFW
# - قواعد iptables
# - قواعد nftables (إن وجدت)
# - المنافذ المستمعة
# - الاتصالات الحالية
#
# يستخدم هذا التقرير لمراجعة إعدادات الحماية
# واكتشاف أي منافذ أو قواعد غير متوقعة.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/firewall_status_report.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                Firewall Status Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Firewall Service Status"

echo "------------------------------------------------------------"

systemctl status ufw --no-pager 2>/dev/null || echo "UFW service is not installed."

echo

echo "UFW Status"

echo "------------------------------------------------------------"

ufw status verbose 2>/dev/null || echo "UFW is not installed."

echo

echo "UFW Rules"

echo "------------------------------------------------------------"

ufw status numbered 2>/dev/null || true

echo

echo "iptables Rules"

echo "------------------------------------------------------------"

iptables -L -n -v 2>/dev/null || echo "iptables is unavailable."

echo

echo "iptables NAT Table"

echo "------------------------------------------------------------"

iptables -t nat -L -n -v 2>/dev/null || true

echo

echo "nftables Rules"

echo "------------------------------------------------------------"

nft list ruleset 2>/dev/null || echo "nftables is unavailable."

echo

echo "Listening Ports"

echo "------------------------------------------------------------"

ss -tuln

echo

echo "Active Connections"

echo "------------------------------------------------------------"

ss -tunap

echo

echo "============================================================"

echo "Firewall Audit Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Firewall audit completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
