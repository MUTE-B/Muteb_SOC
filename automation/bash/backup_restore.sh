#!/bin/bash

# ==========================================================
# الملف:
# backup_restore.sh
#
# الهدف:
# إنشاء واستعادة النسخ الاحتياطية الخاصة بالمشروع.
#
# يقوم هذا السكربت بـ:
#
# - إنشاء نسخة احتياطية مضغوطة.
# - استعادة نسخة احتياطية.
# - عرض جميع النسخ الاحتياطية.
#
# يستخدم للحفاظ على ملفات المشروع
# قبل إجراء أي تحديثات أو تعديلات كبيرة.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد النسخ الاحتياطية
# ----------------------------------------------------------

BACKUP_DIR="$PROJECT_ROOT/backup"


# ----------------------------------------------------------
# إنشاء مجلد النسخ الاحتياطية إذا لم يكن موجوداً
# ----------------------------------------------------------

mkdir -p "$BACKUP_DIR"


# ----------------------------------------------------------
# إنشاء اسم النسخة الاحتياطية
# ----------------------------------------------------------

BACKUP_NAME="Muteb-SOC-$(date +%Y-%m-%d_%H-%M-%S).tar.gz"


# ----------------------------------------------------------
# إنشاء نسخة احتياطية
# ----------------------------------------------------------

create_backup() {

echo

echo "Creating backup..."

tar \
--exclude="./backup" \
--exclude="./venv" \
--exclude="./.git" \
--exclude="./__pycache__" \
-czpf "$BACKUP_DIR/$BACKUP_NAME" .

echo

echo "Backup created successfully."

echo

echo "$BACKUP_DIR/$BACKUP_NAME"

}


# ----------------------------------------------------------
# استعادة نسخة احتياطية
# ----------------------------------------------------------

restore_backup() {

echo

echo "Available Backups"

echo "------------------------------------------------------------"

ls -lh "$BACKUP_DIR"

echo

read -p "Enter backup filename: " FILE

if [ ! -f "$BACKUP_DIR/$FILE" ]; then

    echo

    echo "Backup file not found."

    exit 1

fi

echo

echo "Restoring backup..."

tar -xzpf "$BACKUP_DIR/$FILE" -C "$PROJECT_ROOT"

echo

echo "Backup restored successfully."

}


# ----------------------------------------------------------
# عرض النسخ الاحتياطية
# ----------------------------------------------------------

list_backups() {

echo

echo "Available Backups"

echo "------------------------------------------------------------"

ls -lh "$BACKUP_DIR"

}


# ----------------------------------------------------------
# القائمة الرئيسية
# ----------------------------------------------------------

clear

echo "============================================================"

echo "             Muteb SOC Backup Manager"

echo "============================================================"

echo

echo "1) Create Backup"

echo "2) Restore Backup"

echo "3) List Backups"

echo "4) Exit"

echo

read -p "Choose an option: " OPTION


case "$OPTION" in

1)

create_backup

;;

2)

restore_backup

;;

3)

list_backups

;;

4)

exit 0

;;

*)

echo

echo "Invalid option."

exit 1

;;

esac


echo

echo "============================================================"

echo "Operation completed successfully."

echo "============================================================"
