#!/bin/bash

# ==========================================================
# الملف:
# memory_monitor.sh
#
# الهدف:
# مراقبة استخدام الذاكرة (RAM) وذاكرة Swap
# وإنشاء تقرير شامل يساعد محلل SOC
# على اكتشاف أي استهلاك غير طبيعي للذاكرة.
#
# يقوم هذا السكربت بعرض:
# - معلومات الذاكرة
# - استخدام Swap
# - أعلى العمليات استهلاكاً للذاكرة
# - معلومات النظام
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/memory_monitor.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "               Memory Monitoring Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Memory Usage"

echo "------------------------------------------------------------"

free -h

echo

echo "Detailed Memory Information"

echo "------------------------------------------------------------"

cat /proc/meminfo

echo

echo "Swap Information"

echo "------------------------------------------------------------"

swapon --show

echo

echo "Virtual Memory Statistics"

echo "------------------------------------------------------------"

vmstat

echo

echo "Top Memory Processes"

echo "------------------------------------------------------------"

ps -eo pid,user,%mem,%cpu,comm --sort=-%mem | head -20

echo

echo "System Uptime"

echo "------------------------------------------------------------"

uptime

echo

echo "============================================================"

echo "Memory Monitoring Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Memory monitoring completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
