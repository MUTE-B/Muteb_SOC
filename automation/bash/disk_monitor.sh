#!/bin/bash

# ==========================================================
# الملف:
# disk_monitor.sh
#
# الهدف:
# مراقبة حالة وحدات التخزين وإنشاء تقرير شامل.
#
# يقوم هذا السكربت بعرض:
# - معلومات الأقراص
# - المساحات المستخدمة
# - نقاط التركيب
# - استهلاك Inodes
# - الأقراص المتصلة
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/disk_monitor.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير إذا لم يكن موجوداً
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                Disk Monitoring Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Disk Usage"

echo "------------------------------------------------------------"

df -h

echo

echo "Disk Usage (Inodes)"

echo "------------------------------------------------------------"

df -i

echo

echo "Mounted File Systems"

echo "------------------------------------------------------------"

mount

echo

echo "Available Block Devices"

echo "------------------------------------------------------------"

lsblk

echo

echo "Disk UUID Information"

echo "------------------------------------------------------------"

blkid

echo

echo "Filesystem Information"

echo "------------------------------------------------------------"

cat /etc/fstab

echo

echo "============================================================"

echo "Disk Monitoring Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Disk monitoring completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
