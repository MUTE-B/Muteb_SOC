#!/bin/bash

# ==========================================================
# الملف:
# cpu_monitor.sh
#
# الهدف:
# مراقبة حالة المعالج (CPU) وإنشاء تقرير شامل.
#
# يقوم هذا السكربت بعرض:
# - معلومات المعالج
# - عدد الأنوية
# - معدل التحميل
# - استهلاك المعالج
# - أكثر العمليات استهلاكاً للمعالج
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/cpu_monitor.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                 CPU Monitoring Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "CPU Information"

echo "------------------------------------------------------------"

lscpu

echo

echo "CPU Load"

echo "------------------------------------------------------------"

uptime

echo

echo "Processor Statistics"

echo "------------------------------------------------------------"

cat /proc/stat

echo

echo "Load Average"

echo "------------------------------------------------------------"

cat /proc/loadavg

echo

echo "Top CPU Processes"

echo "------------------------------------------------------------"

ps -eo pid,user,%cpu,%mem,comm --sort=-%cpu | head -20

echo

echo "Current CPU Usage"

echo "------------------------------------------------------------"

top -bn1 | head -20

echo

echo "============================================================"

echo "CPU Monitoring Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "CPU monitoring completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
