#!/bin/bash

# ==========================================================
# الملف:
# network_inventory.sh
#
# الهدف:
# جمع معلومات الشبكة الحالية وحفظها داخل تقرير.
#
# يقوم هذا السكربت بعرض:
# - اسم الجهاز
# - اسم النظام
# - عنوان IP
# - Gateway
# - DNS
# - الواجهات
# - المنافذ المفتوحة
#
# يستخدم لأغراض الجرد الأمني داخل بيئة SOC.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد مسار المشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

REPORT_DIR="$PROJECT_ROOT/reports"

REPORT_FILE="$REPORT_DIR/network_inventory.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير إذا لم يكن موجوداً
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "              Network Inventory Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Operating System"

echo "------------------------------------------------------------"

hostnamectl

echo

echo "Network Interfaces"

echo "------------------------------------------------------------"

ip address

echo

echo "Routing Table"

echo "------------------------------------------------------------"

ip route

echo

echo "Default Gateway"

echo "------------------------------------------------------------"

ip route | grep default

echo

echo "DNS Configuration"

echo "------------------------------------------------------------"

cat /etc/resolv.conf

echo

echo "Listening TCP Ports"

echo "------------------------------------------------------------"

ss -tuln

echo

echo "ARP Cache"

echo "------------------------------------------------------------"

ip neigh

echo

echo "Network Statistics"

echo "------------------------------------------------------------"

ip -s link

echo

echo "============================================================"

echo "Inventory Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص للمستخدم
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Network inventory completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
