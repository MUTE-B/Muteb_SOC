#!/bin/bash

# ==========================================================
# الملف:
# update_checker.sh
#
# الهدف:
# التحقق من حالة تحديثات النظام دون تثبيتها.
#
# يقوم هذا السكربت بعرض:
#
# - إصدار Ubuntu
# - إصدار Kernel
# - آخر عملية تحديث
# - الحزم القابلة للتحديث
# - عدد التحديثات المتوفرة
# - حالة إعادة التشغيل
#
# يستخدم أثناء المراجعات الأمنية للتأكد
# من أن النظام محدث ويحتوي على آخر التصحيحات.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/update_checker_report.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# تحديث قائمة المستودعات
# ----------------------------------------------------------

sudo apt update >/dev/null


# ----------------------------------------------------------
# حساب عدد الحزم القابلة للتحديث
# ----------------------------------------------------------

UPDATES=$(apt list --upgradable 2>/dev/null | tail -n +2 | wc -l)


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                 Update Checker Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Operating System"

echo "------------------------------------------------------------"

hostnamectl

echo

echo "Kernel Version"

echo "------------------------------------------------------------"

uname -r

echo

echo "Available Updates"

echo "------------------------------------------------------------"

apt list --upgradable 2>/dev/null

echo

echo "Number of Available Updates"

echo "------------------------------------------------------------"

echo "$UPDATES"

echo

echo "Reboot Required"

echo "------------------------------------------------------------"

if [ -f /var/run/reboot-required ]; then
    echo "Yes"
else
    echo "No"
fi

echo

echo "Last APT History"

echo "------------------------------------------------------------"

tail -30 /var/log/apt/history.log 2>/dev/null || true

echo

echo "============================================================"

echo "Update Check Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "System update check completed successfully."

echo

echo "Available Updates : $UPDATES"

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
