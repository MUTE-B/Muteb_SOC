#!/bin/bash

# ==========================================================
# الملف:
# log_collector.sh
#
# الهدف:
# جمع أهم سجلات النظام الأمنية داخل تقرير واحد.
#
# يقوم هذا السكربت بجمع:
#
# - معلومات النظام
# - سجلات SSH
# - سجلات المصادقة
# - سجلات Kernel
# - سجلات Systemd
# - آخر عمليات تسجيل الدخول
# - المستخدمين الحاليين
#
# يستخدم هذا التقرير أثناء التحقيقات الأمنية
# وتحليل الحوادث داخل بيئة SOC.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/system_logs_report.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                 System Log Collection"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Current User"

echo "------------------------------------------------------------"

whoami

echo

echo "Current Logged Users"

echo "------------------------------------------------------------"

who

echo

echo "Last Login History"

echo "------------------------------------------------------------"

last | head -30

echo

echo "Authentication Log"

echo "------------------------------------------------------------"

if [ -f /var/log/auth.log ]; then

    tail -200 /var/log/auth.log

else

    echo "Authentication log not found."

fi

echo

echo "Kernel Log"

echo "------------------------------------------------------------"

dmesg | tail -100

echo

echo "System Journal"

echo "------------------------------------------------------------"

journalctl -n 100 --no-pager

echo

echo "SSH Service Status"

echo "------------------------------------------------------------"

systemctl status ssh --no-pager

echo

echo "Failed Login Attempts"

echo "------------------------------------------------------------"

grep "Failed password" /var/log/auth.log 2>/dev/null || true

echo

echo "Successful Login Attempts"

echo "------------------------------------------------------------"

grep "Accepted password" /var/log/auth.log 2>/dev/null || true

echo

echo "============================================================"

echo "Log Collection Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "System log collection completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
