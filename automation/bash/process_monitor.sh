#!/bin/bash

# ==========================================================
# الملف:
# process_monitor.sh
#
# الهدف:
# مراقبة العمليات (Processes) العاملة داخل النظام
# وإنشاء تقرير يساعد محلل SOC في مراجعة العمليات.
#
# يقوم هذا السكربت بعرض:
# - وقت إنشاء التقرير
# - العمليات الأكثر استهلاكاً للمعالج
# - العمليات الأكثر استهلاكاً للذاكرة
# - جميع العمليات الحالية
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد مسار المشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

REPORT_DIR="$PROJECT_ROOT/reports"

REPORT_FILE="$REPORT_DIR/process_monitor.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "              Process Monitoring Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Top CPU Processes"

echo "------------------------------------------------------------"

ps -eo pid,user,%cpu,%mem,comm --sort=-%cpu | head -20

echo

echo "Top Memory Processes"

echo "------------------------------------------------------------"

ps -eo pid,user,%cpu,%mem,comm --sort=-%mem | head -20

echo

echo "Running Processes"

echo "------------------------------------------------------------"

ps -ef

echo

echo "Process Tree"

echo "------------------------------------------------------------"

ps -ejH

echo

echo "============================================================"

echo "Process Monitoring Completed"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Process monitoring completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
