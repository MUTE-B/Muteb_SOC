#!/bin/bash

# ==========================================================
# الملف:
# package_audit.sh
#
# الهدف:
# إجراء تدقيق شامل للحزم المثبتة داخل النظام.
#
# يقوم هذا السكربت بعرض:
#
# - إصدار Ubuntu
# - إصدار Kernel
# - جميع الحزم المثبتة
# - آخر الحزم المثبتة
# - الحزم القابلة للتحديث
# - حجم ذاكرة التخزين المؤقت لـ APT
# - مصادر المستودعات
#
# يستخدم هذا التقرير لمعرفة حالة النظام
# ومراجعة البرمجيات المثبتة أثناء التحقيقات الأمنية.
# ==========================================================


set -e


# ----------------------------------------------------------
# تحديد المجلد الرئيسي للمشروع
# ----------------------------------------------------------

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"


# ----------------------------------------------------------
# تحديد مجلد التقارير
# ----------------------------------------------------------

REPORT_DIR="$PROJECT_ROOT/reports"


# ----------------------------------------------------------
# تحديد اسم التقرير
# ----------------------------------------------------------

REPORT_FILE="$REPORT_DIR/package_audit_report.txt"


# ----------------------------------------------------------
# إنشاء مجلد التقارير
# ----------------------------------------------------------

mkdir -p "$REPORT_DIR"


# ----------------------------------------------------------
# إنشاء التقرير
# ----------------------------------------------------------

{

echo "============================================================"

echo "                  Package Audit Report"

echo "============================================================"

echo

echo "Generated : $(date)"

echo

echo "Hostname"

echo "------------------------------------------------------------"

hostname

echo

echo "Operating System"

echo "------------------------------------------------------------"

hostnamectl

echo

echo "Kernel Version"

echo "------------------------------------------------------------"

uname -r

echo

echo "Installed Packages"

echo "------------------------------------------------------------"

dpkg -l

echo

echo "Upgradeable Packages"

echo "------------------------------------------------------------"

apt list --upgradable 2>/dev/null

echo

echo "APT Repository Sources"

echo "------------------------------------------------------------"

cat /etc/apt/sources.list

echo

echo "Additional Repository Files"

echo "------------------------------------------------------------"

find /etc/apt/sources.list.d -type f -exec cat {} \;

echo

echo "APT Cache Size"

echo "------------------------------------------------------------"

du -sh /var/cache/apt 2>/dev/null

echo

echo "Package Manager History"

echo "------------------------------------------------------------"

tail -100 /var/log/apt/history.log 2>/dev/null

echo

echo "============================================================"

echo "Package Audit Completed Successfully"

echo "============================================================"

} > "$REPORT_FILE"


# ----------------------------------------------------------
# عرض ملخص التنفيذ
# ----------------------------------------------------------

echo

echo "============================================================"

echo "Package audit completed successfully."

echo

echo "Report saved to:"

echo

echo "$REPORT_FILE"

echo

echo "============================================================"
