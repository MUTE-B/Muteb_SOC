#!/bin/bash


# =====================================================
# Muteb SOC User Audit Script
#
# الهدف:
# مراجعة حسابات المستخدمين والصلاحيات داخل Linux
#
# يقوم السكربت بجمع:
# - المستخدم الحالي
# - المستخدمين الموجودين
# - مستخدمي sudo
# - معلومات تسجيل الدخول
# - الحسابات غير التفاعلية
# =====================================================



# إيقاف السكربت عند حدوث خطأ

set -e



# ملف التقرير

REPORT="user_audit_report.txt"



# حذف التقرير القديم

rm -f $REPORT





echo "=================================" >> $REPORT

echo "       Muteb SOC User Audit       " >> $REPORT

echo "=================================" >> $REPORT



echo "" >> $REPORT





# =====================================================
# المستخدم الحالي
# =====================================================


echo "[+] Current User" >> $REPORT


whoami >> $REPORT





# =====================================================
# جميع المستخدمين
# =====================================================


echo "" >> $REPORT

echo "[+] System Users" >> $REPORT



cut -d: -f1 /etc/passwd >> $REPORT





# =====================================================
# المستخدمون أصحاب sudo
# =====================================================


echo "" >> $REPORT

echo "[+] Sudo Group Members" >> $REPORT



getent group sudo >> $REPORT





# =====================================================
# آخر عمليات تسجيل الدخول
# =====================================================


echo "" >> $REPORT

echo "[+] Last Login Activity" >> $REPORT



last >> $REPORT





# =====================================================
# المستخدمون الذين لديهم Shell
# =====================================================


echo "" >> $REPORT

echo "[+] Interactive Users" >> $REPORT



cat /etc/passwd | grep -E "/bin/bash|/bin/zsh" >> $REPORT





# =====================================================
# الحسابات بدون تسجيل دخول
# =====================================================


echo "" >> $REPORT

echo "[+] Non Interactive Accounts" >> $REPORT



cat /etc/passwd | grep "nologin" >> $REPORT





# =====================================================
# نهاية التقرير
# =====================================================


echo "" >> $REPORT


echo "User Audit Completed" >> $REPORT



echo "================================="

echo "User Audit Finished"

echo "Report saved: $REPORT"

echo "================================="
