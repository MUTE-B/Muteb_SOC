# إنشاء المجلدات والتعامل مع الملفات
from pathlib import Path

# الحصول على التاريخ والوقت
from datetime import datetime


# ----------------------------------------------------------
# إنشاء مجلد إذا لم يكن موجوداً
# ----------------------------------------------------------

def create_directory(directory_path):
    """
    إنشاء مجلد في حال عدم وجوده.
    """

    Path(directory_path).mkdir(
        parents=True,
        exist_ok=True
    )


# ----------------------------------------------------------
# إنشاء الوقت الحالي
# ----------------------------------------------------------

def current_time():
    """
    إرجاع التاريخ والوقت الحالي.
    """

    return datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )


# ----------------------------------------------------------
# كتابة تقرير نصي
# ----------------------------------------------------------

def write_report(report_name, content):
    """
    إنشاء تقرير نصي أو استبدال محتواه.
    """

    with open(

        report_name,

        "w",

        encoding="utf-8"

    ) as report:

        report.write(content)


# ----------------------------------------------------------
# إضافة سطر داخل تقرير موجود
# ----------------------------------------------------------

def append_report(report_name, content):
    """
    إضافة معلومات جديدة إلى نهاية التقرير.
    """

    with open(

        report_name,

        "a",

        encoding="utf-8"

    ) as report:

        report.write(content)


# ----------------------------------------------------------
# قراءة تقرير
# ----------------------------------------------------------

def read_report(report_name):
    """
    قراءة محتوى تقرير بالكامل.
    """

    with open(

        report_name,

        "r",

        encoding="utf-8"

    ) as report:

        return report.read()


# ----------------------------------------------------------
# إنشاء عنوان موحد للتقارير
# ----------------------------------------------------------

def report_header(title):
    """
    إنشاء عنوان موحد لجميع تقارير المشروع.
    """

    line = "=" * 60

    return (

        f"{line}\n"

        f"{title}\n"

        f"{line}\n"

        f"Generated: {current_time()}\n\n"

    )
