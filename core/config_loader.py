#!/usr/bin/env python3

# ==========================================================
# ملف: config_loader.py
#
# الهدف:
# قراءة ملف إعدادات المشروع (config.ini)
# وإتاحة الوصول إلى جميع الإعدادات من أي برنامج.
#
# الفائدة:
# يمنع تكرار القيم داخل السكربتات،
# ويسهل تعديل المشروع مستقبلاً.
# ==========================================================


# ----------------------------------------------------------
# استيراد المكتبات
# ----------------------------------------------------------

# مكتبة قراءة ملفات INI
import configparser

# مكتبة التعامل مع الملفات والمسارات
from pathlib import Path


# ----------------------------------------------------------
# تحديد المسار الرئيسي للمشروع
# ----------------------------------------------------------

# الحصول على المجلد الرئيسي للمشروع بشكل تلقائي
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# تحديد موقع ملف الإعدادات
CONFIG_FILE = PROJECT_ROOT / "config" / "config.ini"


# ----------------------------------------------------------
# إنشاء قارئ الإعدادات
# ----------------------------------------------------------

config = configparser.ConfigParser()


# ----------------------------------------------------------
# قراءة ملف الإعدادات
# ----------------------------------------------------------

if not CONFIG_FILE.exists():

    raise FileNotFoundError(

        f"Configuration file not found: {CONFIG_FILE}"

    )

config.read(CONFIG_FILE)


# ----------------------------------------------------------
# دوال الوصول إلى الإعدادات
# ----------------------------------------------------------

def get(section, option):
    """
    إرجاع قيمة نصية من ملف الإعدادات.
    """
    return config.get(section, option)


def get_int(section, option):
    """
    إرجاع قيمة رقمية صحيحة.
    """
    return config.getint(section, option)


def get_float(section, option):
    """
    إرجاع قيمة عشرية.
    """
    return config.getfloat(section, option)


def get_bool(section, option):
    """
    إرجاع قيمة منطقية.
    """
    return config.getboolean(section, option)
