# التحقق من وجود أمر داخل النظام
command_exists() {

    local command_name="$1"

    command -v "$command_name" >/dev/null 2>&1

}

# التحقق من وجود ملف
file_exists() {

    local file_path="$1"

    [[ -f "$file_path" ]]

}

# التحقق من وجود مجلد
directory_exists() {

    local directory_path="$1"

    [[ -d "$directory_path" ]]

}

# إنشاء مجلد إذا لم يكن موجودًا
create_directory() {

    local directory_path="$1"

    if [[ ! -d "$directory_path" ]]; then
        mkdir -p "$directory_path"
    fi

}

