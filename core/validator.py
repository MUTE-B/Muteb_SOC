# للتحقق من صحة عناوين IP
import ipaddress

# للتعامل مع الملفات والمجلدات
from pathlib import Path


# ----------------------------------------------------------
# التحقق من صحة عنوان IP
# ----------------------------------------------------------

def validate_ip(ip_address):

    """
    التحقق من أن عنوان IP مكتوب بصيغة صحيحة.
    """

    try:

        ipaddress.ip_address(ip_address)

        return True

    except ValueError:

        return False


# ----------------------------------------------------------
# التحقق من رقم المنفذ
# ----------------------------------------------------------

def validate_port(port):

    """
    التأكد من أن رقم المنفذ يقع بين 1 و 65535.
    """

    return 1 <= port <= 65535


# ----------------------------------------------------------
# التحقق من وجود ملف
# ----------------------------------------------------------

def file_exists(file_path):

    """
    التأكد من وجود الملف.
    """

    return Path(file_path).is_file()


# ----------------------------------------------------------
# التحقق من وجود مجلد
# ----------------------------------------------------------

def directory_exists(directory_path):

    """
    التأكد من وجود المجلد.
    """

    return Path(directory_path).is_dir()


# ----------------------------------------------------------
# إنشاء مجلد إذا لم يكن موجوداً
# ----------------------------------------------------------

def ensure_directory(directory_path):

    """
    إنشاء المجلد تلقائياً إذا لم يكن موجوداً.
    """

    Path(directory_path).mkdir(

        parents=True,

        exist_ok=True

    )


# ----------------------------------------------------------
# التحقق من أن النص ليس فارغاً
# ----------------------------------------------------------

def validate_text(text):

    """
    التأكد من أن المستخدم أدخل قيمة صحيحة.
    """

    return bool(text.strip())
